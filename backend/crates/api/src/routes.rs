//! Configuration des routes HTTP — séparé de main.rs pour lisibilité.
use actix_web::web;

pub fn configurer(cfg: &mut web::ServiceConfig) {
    cfg.route("/health", web::get().to(crate::handlers::health_check))
        .route(
            "/api/assets",
            web::get().to(crate::assets_handlers::lister_assets),
        )
        .route(
            "/api/assets",
            web::post().to(crate::assets_handlers::ajouter_asset),
        )
        .route(
            "/api/assets/{id}",
            web::delete().to(crate::assets_handlers::supprimer_asset),
        )
        .route("/api/prix", web::get().to(crate::prix_handlers::get_prix))
        .route("/api/candles", web::get().to(crate::handlers::get_candles))
        .route(
            "/api/prix-actuel",
            web::get().to(crate::handlers::get_prix_actuel),
        )
        .route(
            "/api/signaux",
            web::get().to(crate::signaux_handlers::get_signaux),
        )
        .route(
            "/api/ml/predict",
            web::get().to(crate::handlers::predict_ml),
        )
        .route(
            "/api/ml/train",
            web::post().to(crate::ml_handlers::entrainer_ml),
        )
        .route(
            "/api/ml/status",
            web::get().to(crate::ml_handlers::statut_ml),
        )
        .route(
            "/api/backtest",
            web::post().to(crate::backtest_handlers::run_backtest),
        )
        .route(
            "/api/backtest/raffiner-ml",
            web::post().to(crate::backtest_handlers::raffiner_ml),
        )
        .route(
            "/api/signaux/export",
            web::post().to(crate::export_handlers::exporter_signaux_csv),
        )
        .route(
            "/api/smc/analyse",
            web::get().to(crate::smc_handlers::analyse_smc),
        )
        .route(
            "/api/indicators",
            web::get().to(crate::indicators_handlers::get_indicators),
        )
        .route(
            "/api/tendance/multi-tf",
            web::get().to(crate::tendance_handlers::tendance_multi_tf),
        )
        .route(
            "/api/ia/analyse",
            web::post().to(crate::ollama_handlers::analyser),
        )
        .route("/api/ia/chat", web::post().to(crate::ollama_handlers::chat))
        .route(
            "/api/ia/chart",
            web::post().to(crate::ollama_handlers::analyser_chart),
        )
        .route(
            "/api/ia/status",
            web::get().to(crate::ollama_handlers::statut),
        )
        .route(
            "/api/ia/signal",
            web::post().to(crate::ollama_handlers::generer_signal),
        )
        .route(
            "/api/ia/ajustements",
            web::post().to(crate::ollama_ajustements_handler::ajustements),
        )
        .route(
            "/api/ia/signal/straddle",
            web::post().to(crate::straddle_signal_handler::generer_signal_straddle),
        )
        .route(
            "/api/straddle/analyser",
            web::post().to(crate::straddle_handlers::analyser),
        )
        .route(
            "/api/straddle/creneaux",
            web::get().to(crate::straddle_handlers::lister_creneaux),
        )
        .route(
            "/api/straddle/creneaux/{id}",
            web::patch().to(crate::straddle_handlers::mettre_a_jour_creneau),
        )
        .route(
            "/api/straddle/creneaux/{id}/precision",
            web::post().to(crate::straddle_handlers::handler_analyser_precision),
        )
        .route(
            "/api/straddle/backtest",
            web::post().to(crate::straddle_backtest_handler::handler_backtest_slot),
        )
        .route(
            "/api/straddle/params",
            web::get().to(crate::strategies_params_handlers::get_straddle_params),
        )
        .route(
            "/api/straddle/params",
            web::put().to(crate::strategies_params_handlers::put_straddle_params),
        )
        .route(
            "/api/smc/params",
            web::get().to(crate::strategies_params_handlers::get_smc_params),
        )
        .route(
            "/api/smc/params",
            web::put().to(crate::strategies_params_handlers::put_smc_params),
        )
        .route(
            "/api/config",
            web::get().to(crate::config_handlers::get_config),
        )
        .route(
            "/api/config",
            web::post().to(crate::config_handlers::post_config),
        )
        .route("/api/ib/status", web::get().to(crate::handlers::ib_status))
        .route(
            "/api/calendar",
            web::get().to(crate::calendar_handlers::get_calendar),
        )
        .route(
            "/api/sentiment/marche",
            web::get().to(crate::sentiment_handlers::get_sentiment_marche),
        )
        .route(
            "/api/news/alertes",
            web::get().to(crate::news_handlers::get_news_alertes),
        )
        .route(
            "/api/news/contenu",
            web::get().to(crate::news_handlers::get_contenu_article),
        )
        .route(
            "/api/news/traduire",
            web::get().to(crate::news_handlers::get_traduire),
        )
        .route(
            "/api/news/fear-greed",
            web::get().to(crate::news_fear_greed::get_fear_greed),
        )
        .route(
            "/api/news/lu",
            web::post().to(crate::news_lus_handlers::marquer_lu),
        )
        .route(
            "/api/news/lus",
            web::get().to(crate::news_lus_handlers::lire_lus),
        )
        .route(
            "/api/news/contexte-marche",
            web::get().to(crate::news_context_handler::get_contexte_marche),
        )
        .route(
            "/api/stream",
            web::get().to(crate::ws_handlers::stream_market),
        )
        .route(
            "/api/signal-engine/start",
            web::post().to(crate::engine_handlers::demarrer_engine),
        )
        .route(
            "/api/signal-engine/stop",
            web::post().to(crate::engine_handlers::arreter_engine),
        )
        .route(
            "/api/signal-engine/status",
            web::get().to(crate::engine_handlers::statut_engine),
        )
        .route(
            "/api/signal-engine/stream",
            web::get().to(crate::engine_handlers::stream_signaux),
        )
        .route(
            "/api/data/coverage",
            web::get().to(crate::data_handlers::get_coverage),
        )
        .route(
            "/api/data/collect",
            web::post().to(crate::data_handlers::post_collect),
        )
        .route(
            "/api/ml/history",
            web::get().to(crate::ml_handlers::historique_ml),
        )
        .route(
            "/api/rockets/signal",
            web::post().to(crate::rockets_handlers::sauvegarder_signal),
        )
        .route(
            "/api/rockets/scan",
            web::get().to(crate::rockets_handlers::get_scan),
        )
        .route(
            "/api/rockets/scan/debug",
            web::get().to(crate::rockets_handlers::scan_momentum_debug),
        )
        .route(
            "/api/rockets/historique",
            web::get().to(crate::rockets_handlers::get_historique),
        )
        .route(
            "/api/rockets/sync",
            web::post().to(crate::rockets_suivi::sync_verdicts),
        )
        .service(
            web::resource("/api/rockets/config")
                .route(web::get().to(crate::rockets_handlers::get_config))
                .route(web::put().to(crate::rockets_handlers::put_config)),
        )
        .service(
            web::resource("/api/rockets/analyse-llm")
                .route(web::get().to(crate::rockets_analyse_handler::get_derniere_analyse))
                .route(web::post().to(crate::rockets_analyse_handler::lancer_analyse)),
        )
        .service(
            web::resource("/api/smc/analyse-llm")
                .route(web::get().to(crate::smc_analyse_handler::get_derniere_analyse))
                .route(web::post().to(crate::smc_analyse_handler::lancer_analyse)),
        )
        .route(
            "/api/volatility/patterns",
            web::get().to(crate::volatility_handlers::get_patterns),
        )
        .route(
            "/api/ia/ab-test",
            web::get().to(crate::ab_test_handlers::get_ab_test),
        );
}
